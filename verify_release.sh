#!/bin/bash
# Offline checks for this release. Needs Python 3.9+ with numpy (checks 1-4 are stdlib-only).
# Usage:  bash verify_release.sh            (or PY=/path/to/python bash verify_release.sh)
# Each check prints PASS/FAIL; the script exits nonzero if any check fails.
# None of these retrains a model: they recompute summaries from the shipped receipts.
set -u
cd "$(dirname "$0")"
PY=${PY:-python3}
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
fails=0
check () {  # $1 name, rest: command
  local name=$1; shift
  if "$@" > "$TMP/log" 2>&1; then echo "PASS  $name"; else echo "FAIL  $name"; tail -5 "$TMP/log"; fails=$((fails+1)); fi
}

# 1. corpus exposure report on the paper's corpus and on the three example manifests
check "leakage_report --demo meg-masc" $PY scripts/leakage_report.py --demo meg-masc
for m in meg-masc brennan2019 libribrain-1sub; do
  check "leakage_report manifest_$m" $PY scripts/leakage_report.py --manifest artifacts/manifest_$m.csv
done
grep -q '4 -> 3   (25% less' <($PY scripts/leakage_report.py --demo meg-masc) \
  && echo "PASS  MEG-MASC fix cost 25%" || { echo "FAIL  MEG-MASC fix cost"; fails=$((fails+1)); }

# 2. split checker must refuse a manifest without a split column (it audits splits, not corpora)
if $PY scripts/stimulus_leakage_check.py --manifest artifacts/manifest_meg-masc.csv > "$TMP/log" 2>&1; then
  echo "FAIL  stimulus_leakage_check accepted a manifest with no split column"; fails=$((fails+1))
else echo "PASS  stimulus_leakage_check refuses an unsplit manifest"; fi

# 3. external one-bit arm readouts (Table 4)
check "verify_onebit_readouts" $PY scripts/verify_onebit_readouts.py

# 4. post-hoc sensitivity intervals (App. C) regenerate the shipped JSON byte-identically
cp results/interaction_sensitivity.json "$TMP/sens.json"
check "interaction_sensitivity runs" $PY scripts/interaction_sensitivity.py
if cmp -s results/interaction_sensitivity.json "$TMP/sens.json"; then echo "PASS  interaction_sensitivity.json unchanged"
else echo "FAIL  interaction_sensitivity.json changed (restored)"; cp "$TMP/sens.json" results/interaction_sensitivity.json; fails=$((fails+1)); fi

# 5. Table 1 (retained fraction) from the per-subject receipts
check "Table 1: retained_fraction --check-published" \
  $PY scripts/retained_fraction.py --check-published --results results/table1_receipts

# 6. calibration-diversity control (App. calmatch): rerun the registered analysis, compare results
check "calmatch analysis rerun" $PY scripts/calmatch_analysis_20260924.py \
  --results results/calmatch_20260924/primary/inputs --receipts results/calmatch_20260924/primary/receipts \
  --out "$TMP/calmatch.json"
check "calmatch results equal shipped analysis.json" $PY - "$TMP/calmatch.json" results/calmatch_20260924/analysis.json <<'EOF'
import json, sys
a, b = (json.load(open(p)) for p in sys.argv[1:3])
# script hashes, timestamps and receipt hashes differ by design (scrubbed copies; see the calmatch README)
skip = {"script_sha256", "generated", "inputs"}
bad = [k for k in set(a) | set(b) if k not in skip and a.get(k) != b.get(k)]
res = [k for k in a["inputs"] if k.startswith("result_") and a["inputs"][k] != b["inputs"].get(k)]
print("differing keys:", bad, "result-file hash mismatches:", res)
sys.exit(1 if bad or res else 0)
EOF

# 7. seed-replicate appendix table and registered branches (App. seeds) from the analysis receipt
check "strengthen_render" $PY scripts/strengthen_render_20260926.py results/strengthen_20260926/analysis_summary.json "$TMP/sr"
for f in appendix_table.tex branch_numbers.txt; do
  cmp -s "$TMP/sr/$f" results/strengthen_20260926/$f && echo "PASS  $f regenerated byte-identically" \
    || { echo "FAIL  $f differs"; fails=$((fails+1)); }
done

# 8. receipt hashes the paper prints
$PY - <<'EOF' && echo "PASS  receipt SHA-256 prefixes match the paper" || { echo "FAIL  receipt SHA-256"; exit 1; }
import hashlib, sys
want = {"results/calmatch_20260924/analysis.json": "a90df8e428c4",
        "results/subjects27_20261004/stage1/stage1_analysis.json": "a211d1c5"}
bad = [p for p, h in want.items() if not hashlib.sha256(open(p, "rb").read()).hexdigest().startswith(h)]
print("mismatch:", bad) if bad else None
sys.exit(1 if bad else 0)
EOF
[ $? -eq 0 ] || fails=$((fails+1))

echo; [ $fails -eq 0 ] && echo "ALL CHECKS PASSED" || echo "$fails CHECK(S) FAILED"
exit $fails
